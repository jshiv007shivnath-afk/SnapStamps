function mapAthleteDefs(
  defs: AthleteSeedDef[],
  discipline: 'cricket' | 'football'
): StampItem[] {
  return defs.map((d) => ({
    id: d.id,
    title: d.name,
    country: d.country,
    city: d.city,
    category: 'sports',
    sportDiscipline: discipline,
    athleteName: d.name,
    celebrationLabel: d.celebration,
    jerseyNumber: d.jerseyNumber,
    rarity: d.rarity,
    collectedCount: 0,
    totalInSet: 1,
    isFavorite: false,
    isUnlocked: false,
    coordinates: { lat: d.lat, lng: d.lng },
    imageUrl:
      d.imageUrl ||
      buildAthleteStampSvg({
        discipline,
        jerseyColor: d.jerseyColor,
        jerseyTrim: d.jerseyTrim,
        jerseyNumber: d.jerseyNumber,
        skyTop: d.skyTop,
        skyBottom: d.skyBottom,
        turfColor: d.turfColor,
        skinTone: d.skinTone,
        pose: d.pose,
      }),
    accentColor: d.accent,
    bannerColor: d.banner,
    pocketId: 'sports-vault',
    description: d.description,
    priceDiamonds: d.price,
  }));
}

